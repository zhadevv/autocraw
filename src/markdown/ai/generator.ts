import type { MarkdownOptions, MarkdownResult, SiteReport } from '../../types';
import { AutocrawError } from '../../utils/errors';
import { buildContext } from './context-builder';
import { systemPrompt, userPrompt } from './prompts';
import { createProvider } from './providers';
import { countTokens } from './token-counter';
import { AICache } from './cache';
import { buildFrontmatter } from '../default/generator';

const DEFAULT_MAX_INPUT = 24000;
const DEFAULT_MAX_OUTPUT = 6000;
const FENCE = '`'.repeat(3);

export function stripWrappingFence(text: string): string {
  const trimmed = text.trim();
  const match = new RegExp(`^${FENCE}(?:markdown|md)?\\s*\\n([\\s\\S]*?)\\n${FENCE}$`, 'i').exec(trimmed);
  return match ? (match[1] as string).trim() : trimmed;
}

export async function generateAiMarkdown(report: SiteReport, options: MarkdownOptions, signal?: AbortSignal): Promise<MarkdownResult> {
  const ai = options.ai;
  if (!ai) throw new AutocrawError('E_CONFIG', 'AI mode requires options.ai with provider and apiKey.');
  if (ai.provider !== 'ollama' && (!ai.apiKey || !ai.apiKey.trim())) throw new AutocrawError('E_CONFIG', `Missing API key for provider "${ai.provider}". Pass --api-key or set the matching environment variable.`);

  const provider = createProvider(ai);
  const maxInput = ai.maxInputTokens ?? DEFAULT_MAX_INPUT;
  const maxOutput = ai.maxOutputTokens ?? DEFAULT_MAX_OUTPUT;
  const warnings: string[] = [];

  const context = buildContext(report, maxInput, options.maxExamples);
  if (context.trimmed.length > 0) warnings.push(`Context trimmed to fit ${maxInput} input tokens: ${context.trimmed.join(', ')}.`);
  const system = systemPrompt(options.language);
  const user = userPrompt(options.template, options.language, context.json);
  const estimatedInput = countTokens(system) + countTokens(user);

  const cache = ai.cache === false ? null : new AICache(ai.cacheDir);
  const cacheKey = cache ? cache.key([provider.name, provider.model, options.template, options.language, String(ai.temperature ?? ''), system, user]) : '';
  if (cache) {
    const hit = await cache.get(cacheKey);
    if (hit) {
      return {
        markdown: finalize(hit.markdown, report, options, provider.name, hit.model),
        mode: 'ai',
        template: options.template,
        usedFallback: false,
        cached: true,
        provider: provider.name,
        model: hit.model,
        inputTokens: hit.inputTokens,
        outputTokens: hit.outputTokens,
        warnings,
      };
    }
  }

  const response = await provider.generate({ system, user, maxOutputTokens: maxOutput, temperature: ai.temperature ?? 0.2, signal });
  const body = stripWrappingFence(response.text);
  if (body.length < 80) throw new AutocrawError('E_AI', `${provider.name} returned an unusably short response (${body.length} characters).`, { provider: provider.name, model: response.model });
  if (response.truncated) warnings.push(`The model hit the output limit of ${maxOutput} tokens; the document may be cut off. Increase maxOutputTokens.`);

  if (cache && !response.truncated) {
    await cache.set(cacheKey, {
      markdown: body,
      provider: provider.name,
      model: response.model,
      inputTokens: response.inputTokens ?? estimatedInput,
      outputTokens: response.outputTokens,
      createdAt: new Date().toISOString(),
    });
  }

  return {
    markdown: finalize(body, report, options, provider.name, response.model),
    mode: 'ai',
    template: options.template,
    usedFallback: false,
    cached: false,
    provider: provider.name,
    model: response.model,
    inputTokens: response.inputTokens ?? estimatedInput,
    outputTokens: response.outputTokens,
    warnings,
  };
}

function finalize(body: string, report: SiteReport, options: MarkdownOptions, provider: string, model: string): string {
  const parts: string[] = [];
  if (options.frontmatter) parts.push(`---\n${buildFrontmatter(report, options, { mode: 'ai', provider, model })}\n---\n`);
  parts.push(body.trim());
  parts.push(`---\n\n*Generated by autocraw ${report.version} using ${provider} (${model}). Verify critical details against the raw report.*`);
  return `${parts.join('\n\n')}\n`;
}
